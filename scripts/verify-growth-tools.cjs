// Set PLAYWRIGHT_MODULE to an external Playwright installation when it is not installed locally.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', (e) => errors.push(e.message));
    const base = process.env.TEST_BASE_URL || 'http://localhost:3100';
    const go = async (path) => {
      await page.goto(base + path, { waitUntil: 'domcontentloaded', timeout: 60000 });
      await page.getByRole('button', { name: /Alternar tema|Toggle theme/ }).waitFor();
    };
    await go('/pt/ferramentas/gerador-link-whatsapp');
    await page.getByLabel('WhatsApp com código do país e DDD').fill('+55 11 99999-9999');
    await page.getByLabel('Mensagem pronta (opcional)', { exact: true }).fill('Olá & ação');
    const generated = await page.getByLabel('Seu link está pronto').inputValue();
    assert.equal(generated, 'https://wa.me/5511999999999?text=Ol%C3%A1%20%26%20a%C3%A7%C3%A3o');
    await page.getByRole('button', { name: 'Copiar link', exact: true }).click();
    await page.getByText('Link copiado!', { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), generated);
    await page.getByLabel('WhatsApp com código do país e DDD').fill('abc');
    assert.equal(await page.getByRole('button', { name: 'Copiar link', exact: true }).count(), 0);
    console.log('PASS WhatsApp: encoding, clipboard and invalid input');
    await go('/pt/ferramentas/criador-links-utm');
    await page.getByLabel('Endereço de destino').fill('https://example.com/oferta?item=2#oferta');
    await page.getByLabel('Nome da campanha', { exact: true }).fill('ação setembro');
    const campaign = new URL(await page.getByLabel('Seu link está pronto').inputValue());
    assert.equal(campaign.searchParams.get('utm_source'), 'instagram');
    assert.equal(campaign.searchParams.get('item'), '2');
    assert.equal(campaign.hash, '#oferta');
    await page.getByRole('button', { name: 'E-mail', exact: true }).click();
    assert.equal(await page.getByLabel('Meio (utm_medium)').inputValue(), 'email');
    console.log('PASS UTM: parameters, anchor and channel preset');
    await go('/pt/ferramentas/simulador-tempo-automacao');
    assert.match(await page.locator('.growth-metrics').innerText(), /15,4/);
    await page.getByLabel('Dias de trabalho por mês').fill('32');
    assert.equal(await page.locator('.growth-metrics').count(), 0);
    await page.getByLabel('Dias de trabalho por mês').fill('22');
    console.log('PASS simulation: default calculation and input boundaries');
    await go('/en/ferramentas/gerador-link-whatsapp');
    await page.getByRole('heading', { name: 'One click starts a conversation.' }).waitFor();
    console.log('PASS English route');
    await go('/pt/ferramentas');
    await page.getByLabel('O que você precisa fazer?').fill('utm');
    assert.equal(await page.locator('.tool-index .tool-chip').count(), 1);
    await page.getByLabel('O que você precisa fazer?').fill('sem-resultado-xyz');
    await page.getByRole('button', { name: 'Limpar filtros' }).click();
    assert.ok(await page.locator('.tool-index .tool-chip').count() >= 22);
    console.log('PASS catalog: search and clear filters');
    fs.mkdirSync('output/verification', { recursive: true });
    await page.screenshot({ path: 'output/verification/tools-desktop.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: 'output/verification/tools-mobile.png' });
    console.log('Overflow audit', await page.evaluate(() => ({width: innerWidth, document: document.documentElement.scrollWidth, elements: [...document.querySelectorAll('main *')].filter(e => e.getBoundingClientRect().right > innerWidth + 1).slice(0,15).map(e => ({tag:e.tagName, class:e.className, width:e.getBoundingClientRect().width}))})));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await go('/pt/ferramentas/simulador-tempo-automacao');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    assert.deepEqual(errors, []);
    console.log('PASS mobile: no horizontal overflow; no uncaught browser errors');
    await go('/pt/ferramentas/plano-digital');
    await page.getByRole('button', { name: 'Melhorar minha imagem', exact: true }).click();
    await page.getByRole('heading', { name: 'Melhorar minha imagem', exact: true }).waitFor();
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Baixar meu plano' }).click();
    assert.equal((await downloadEvent).suggestedFilename(), 'meu-plano-digital.txt');
    await go('/pt');
    await page.screenshot({ path: 'output/verification/home-mobile.png' });
    console.log('Home overflow', await page.evaluate(() => ({width:innerWidth,document:document.documentElement.scrollWidth,elements:[...document.querySelectorAll('main *')].filter(e=>e.getBoundingClientRect().right>innerWidth+1).slice(0,20).map(e=>({tag:e.tagName,class:e.className,width:e.getBoundingClientRect().width}))})));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: 'output/verification/home-desktop.png' });
    assert.deepEqual(errors, []);
    console.log('PASS planner: priority selection, file download and homepage');
  } finally { await browser.close(); }
})().catch((e) => { console.error(e); process.exit(1); });
